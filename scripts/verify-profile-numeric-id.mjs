/**
 * Verifies migration 006_profile_numeric_id.sql against the live database.
 *
 *   node scripts/verify-profile-numeric-id.mjs
 *
 * Run it AFTER applying supabase/sql/006_profile_numeric_id.sql. It answers,
 * with evidence rather than assertion, every post-migration question:
 *
 *   1. existing profiles survived, with their auth uuids intact
 *   2. a new profile gets the next numeric id automatically
 *   3. several in a row come out sequential
 *   4. authentication still maps: profiles.user_id -> auth.users.id, FK intact
 *   5. the pre-migration backup table is present
 *   6. RLS policies exist and compare against user_id
 *   7. the signup triggers are still attached and rewritten
 *   8. the identity sequence is past the backfill
 *
 * SAFETY. This script never commits a write. Checks 2 and 3 insert profile
 * rows inside a transaction that is ALWAYS rolled back — the ids they consume
 * are burned (sequences do not roll back, by design, so that concurrent
 * inserts cannot collide), but no row and no data change survives. There is no
 * DROP, DELETE or TRUNCATE anywhere in this file.
 *
 * It connects on DIRECT_URL, not DATABASE_URL: the pooled connection runs
 * pgbouncer in transaction mode, which cannot hold the interactive transaction
 * checks 2 and 3 need.
 */

import { PrismaClient } from "@prisma/client";
import { readFileSync } from "node:fs";

// .env is read by hand: this script runs under plain node, without Next's
// loader, and must not depend on dotenv being installed.
for (const line of readFileSync(".env", "utf8").split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (match) process.env[match[1]] ??= match[2].trim().replace(/^["']|["']$/g, "");
}

const url = process.env.DIRECT_URL ?? process.env.DATABASE_URL;
if (!url) {
    console.error("DIRECT_URL (or DATABASE_URL) must be set in .env");
    process.exit(1);
}

const prisma = new PrismaClient({ datasources: { db: { url } } });

/** Sentinel that unwinds the interactive transaction without it being a failure. */
const ROLLBACK = Symbol("rollback");

let failures = 0;

const pass = (label, detail) => console.log(`  PASS  ${label}${detail ? ` — ${detail}` : ""}`);
const fail = (label, detail) => {
    failures += 1;
    console.log(`  FAIL  ${label}${detail ? ` — ${detail}` : ""}`);
};
const check = (condition, label, detail) => (condition ? pass(label, detail) : fail(label, detail));

const section = (title) => console.log(`\n${title}`);

// BigInt is not JSON-serializable and reads badly in template strings.
const plain = (value) => (typeof value === "bigint" ? Number(value) : value);

try {
    // ── 1. Shape ─────────────────────────────────────────────────────
    section("1. Column shape");

    const columns = await prisma.$queryRawUnsafe(`
        SELECT column_name, data_type, is_identity, identity_generation, is_nullable
          FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = 'profiles'
           AND column_name IN ('id', 'user_id')
    `);
    const byName = Object.fromEntries(columns.map((c) => [c.column_name, c]));

    check(byName.id?.data_type === "bigint", "id is bigint", byName.id?.data_type);
    check(byName.id?.is_identity === "YES", "id is an identity column", byName.id?.is_identity);
    check(
        byName.id?.identity_generation === "BY DEFAULT",
        "id is GENERATED BY DEFAULT",
        byName.id?.identity_generation
    );
    check(byName.user_id?.data_type === "uuid", "user_id is uuid", byName.user_id?.data_type);

    // ── 2. Auth mapping ──────────────────────────────────────────────
    section("2. Authentication mapping");

    const fks = await prisma.$queryRawUnsafe(`
        SELECT conname, pg_get_constraintdef(oid) AS def
          FROM pg_constraint
         WHERE conrelid = 'public.profiles'::regclass AND contype = 'f'
    `);
    const authFk = fks.find((f) => /REFERENCES auth\.users\(id\)/.test(f.def));
    check(Boolean(authFk), "user_id still references auth.users(id)", authFk?.def);
    check(
        Boolean(authFk && /ON DELETE CASCADE/.test(authFk.def)),
        "the FK still cascades on auth user deletion"
    );

    const uniques = await prisma.$queryRawUnsafe(`
        SELECT conname, pg_get_constraintdef(oid) AS def
          FROM pg_constraint
         WHERE conrelid = 'public.profiles'::regclass AND contype IN ('u', 'p')
    `);
    check(
        uniques.some((u) => /UNIQUE \("?user_id"?\)/.test(u.def)),
        "user_id is UNIQUE (one profile per auth user, and the ON CONFLICT target)"
    );
    check(
        uniques.some((u) => /PRIMARY KEY \("?id"?\)/.test(u.def)),
        "id is the PRIMARY KEY"
    );

    const [orphans] = await prisma.$queryRawUnsafe(`
        SELECT count(*)::int AS n
          FROM public.profiles p
          LEFT JOIN auth.users u ON u.id = p.user_id
         WHERE u.id IS NULL
    `);
    check(orphans.n === 0, "every profile maps to a real auth user", `${orphans.n} orphaned`);

    // ── 3. Existing data ─────────────────────────────────────────────
    section("3. Existing data preserved");

    const rows = await prisma.$queryRawUnsafe(`
        SELECT id, user_id, email, created_at
          FROM public.profiles ORDER BY id
    `);
    check(rows.length > 0, "profiles are retrievable", `${rows.length} row(s)`);
    for (const row of rows) {
        console.log(`        #${plain(row.id)}  ${row.email}  ${row.user_id}`);
    }

    const sequential = rows.every((row, index) => Number(row.id) === index + 1);
    check(sequential, "existing ids are 1..N with no gaps");

    const [backup] = await prisma.$queryRawUnsafe(`
        SELECT to_regclass('public.profiles_backup_20260909') IS NOT NULL AS present
    `);
    check(backup.present, "the pre-migration backup table is present");

    if (backup.present) {
        const [counts] = await prisma.$queryRawUnsafe(`
            SELECT (SELECT count(*)::int FROM public.profiles) AS now,
                   (SELECT count(*)::int FROM public.profiles_backup_20260909) AS before
        `);
        check(
            counts.now >= counts.before,
            "no profile was lost in the migration",
            `${counts.before} before, ${counts.now} now`
        );
    }

    // ── 4. Sequence ──────────────────────────────────────────────────
    section("4. Identity sequence");

    const [seq] = await prisma.$queryRawUnsafe(`
        SELECT last_value, is_called FROM public.profiles_id_seq
    `);
    const [maxRow] = await prisma.$queryRawUnsafe(
        `SELECT coalesce(max(id), 0) AS max FROM public.profiles`
    );
    const nextId = Number(seq.last_value) + (seq.is_called ? 1 : 0);
    check(
        nextId > Number(maxRow.max),
        "the sequence is past every existing id (signup cannot collide)",
        `next = ${nextId}, max = ${plain(maxRow.max)}`
    );

    // ── 5. RLS ───────────────────────────────────────────────────────
    section("5. Row level security");

    const [rls] = await prisma.$queryRawUnsafe(
        `SELECT relrowsecurity FROM pg_class WHERE oid = 'public.profiles'::regclass`
    );
    check(rls.relrowsecurity, "RLS is enabled on public.profiles");

    const policies = await prisma.$queryRawUnsafe(`
        SELECT policyname, cmd, qual, with_check
          FROM pg_policies WHERE schemaname = 'public' AND tablename = 'profiles'
    `);
    for (const name of ["profiles_select_own", "profiles_insert_own", "profiles_update_own"]) {
        const policy = policies.find((p) => p.policyname === name);
        const expression = `${policy?.qual ?? ""} ${policy?.with_check ?? ""}`;
        check(
            Boolean(policy) && expression.includes("user_id"),
            `${name} compares auth.uid() against user_id`,
            policy ? expression.trim() : "missing"
        );
    }
    const update = policies.find((p) => p.policyname === "profiles_update_own");
    check(
        Boolean(update?.qual && update?.with_check),
        "the UPDATE policy keeps BOTH USING and WITH CHECK (no user_id reassignment)"
    );
    check(
        !policies.some((p) => p.cmd === "DELETE"),
        "there is still no DELETE policy (profiles go only via the cascade)"
    );

    // ── 6. Triggers ──────────────────────────────────────────────────
    section("6. Signup triggers");

    const triggers = await prisma.$queryRawUnsafe(`
        SELECT tgname FROM pg_trigger
         WHERE tgrelid = 'auth.users'::regclass AND NOT tgisinternal
    `);
    for (const name of ["on_auth_user_created", "on_auth_user_email_updated"]) {
        check(
            triggers.some((t) => t.tgname === name),
            `${name} is still attached to auth.users`
        );
    }

    const [handler] = await prisma.$queryRawUnsafe(`
        SELECT pg_get_functiondef(oid) AS def
          FROM pg_proc WHERE proname = 'handle_new_auth_user'
    `);
    check(
        Boolean(handler) && handler.def.includes("on conflict (user_id)"),
        "handle_new_auth_user conflicts on user_id"
    );
    check(
        Boolean(handler) && !/insert into public\.profiles \(id,/.test(handler.def),
        "handle_new_auth_user no longer inserts an id (the identity supplies it)"
    );

    // ── 7 & 8. Allocation, in a transaction that is always rolled back ─
    section("7. Automatic sequential allocation (inserted, then rolled back)");

    const spare = await prisma.$queryRawUnsafe(`
        SELECT u.id FROM auth.users u
         WHERE NOT EXISTS (SELECT 1 FROM public.profiles p WHERE p.user_id = u.id)
         LIMIT 3
    `);

    if (spare.length < 2) {
        console.log(
            "  SKIP  needs 2 auth users without a profile to test allocation " +
                `(found ${spare.length}); the sequence check above still covers the risk`
        );
    } else {
        const before = Number(maxRow.max);
        let allocated = [];

        try {
            await prisma.$transaction(async (tx) => {
                for (const [index, user] of spare.slice(0, 2).entries()) {
                    // `id` is deliberately not supplied — that is the thing
                    // under test.
                    const created = await tx.profile.create({
                        data: {
                            userId: user.id,
                            firstName: "Verification",
                            lastName: `Probe ${index + 1}`,
                            email: `verify-probe-${index + 1}@example.invalid`,
                        },
                    });
                    allocated.push(Number(created.id));
                }
                throw ROLLBACK;
            });
        } catch (error) {
            if (error !== ROLLBACK) throw error;
        }

        check(
            allocated[0] === before + 1,
            "a new profile is given the next numeric id automatically",
            `expected ${before + 1}, got ${allocated[0]}`
        );
        check(
            allocated[1] === allocated[0] + 1,
            "consecutive profiles are sequential",
            allocated.join(", ")
        );

        const [after] = await prisma.$queryRawUnsafe(
            `SELECT count(*)::int AS n FROM public.profiles`
        );
        check(
            after.n === rows.length,
            "the probe rows were rolled back; nothing was persisted",
            `${after.n} row(s)`
        );
    }

    section(failures === 0 ? "All checks passed." : `${failures} check(s) FAILED.`);
    process.exitCode = failures === 0 ? 0 : 1;
} catch (error) {
    console.error("\nVerification could not complete:", error.message);
    process.exitCode = 1;
} finally {
    await prisma.$disconnect();
}
